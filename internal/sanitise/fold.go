// Static Latin decomposition/fold table (research.md R1): generated once
// from Unicode NFKD decomposition data (Python unicodedata, Unicode 15) and
// checked in as ordinary Go source so output can never drift with Unicode
// version changes (NFR-002). Covers Latin-1 Supplement, Latin Extended-A/B
// letters with an ASCII base, and the Alphabetic Presentation Forms
// ligatures. Codepoints with explicit PRD entries live in internal/table.
package sanitise

import "sort"

// Fold returns the ASCII base-letter fallback for r (FR-014).
func Fold(r rune) (string, bool) {
	rep, ok := foldTable[r]
	return rep, ok
}

// IsCombining reports whether r is a combining diacritical mark that may be
// dropped after its base letter is emitted (NFD-form input parity). Covers
// the Combining Diacritical Marks block and its Extended, Supplement, For
// Symbols, and Half Marks blocks.
func IsCombining(r rune) bool {
	return (r >= 0x0300 && r <= 0x036F) ||
		(r >= 0x1AB0 && r <= 0x1AFF) ||
		(r >= 0x1DC0 && r <= 0x1DFF) ||
		(r >= 0x20D0 && r <= 0x20FF) ||
		(r >= 0xFE20 && r <= 0xFE2F)
}

// FoldKeys returns all folded codepoints in ascending order (tests only).
func FoldKeys() []rune {
	keys := make([]rune, 0, len(foldTable))
	for r := range foldTable {
		keys = append(keys, r)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	return keys
}

